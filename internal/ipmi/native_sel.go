// Native event log: a port of ipmitool 1.8.19's "sel list"
// (ipmi_sel_print_std_entry in lib/ipmi_sel.c, without the SDR lookup that
// only "sel elist" does), giving the SELEntry values parseSEL gives:
//   - ID: the record ID in hex ("%4x", here unpadded as parseSEL trims);
//   - Event: the sensor type name, " #0x%02x" with the sensor number unless
//     it is 0, ": ", then the event description;
//   - Direction: "Asserted" or "Deasserted";
//   - Timestamp: one deliberate difference. ipmitool prints the date in the
//     C locale's %x, which reads differently per machine ("24/02/26" under
//     en_GB, "02/24/26" under en_US); fyrtaarn prints "2006-01-02 15:04:05
//     MST" in the local time zone, which reads the same everywhere. A time
//     before 0x20000000 (early 1987) is a BMC clock not yet set: ipmitool
//     prints "Pre-Init" and the raw seconds, and so does this.

//
// Sensor type names and event descriptions come from ipmitool's own tables
// (ipmitool_tables_gen.go, generated by scripts/gen-ipmi-tables.py), looked
// up as ipmi_get_sensor_type and ipmi_get_event_desc do. go-ipmi has its
// own tables, but their wording differs ("Power Off / Power Down" for
// ipmitool's "Power off/down") and they ignore event data 2, which turns
// ipmitool's "No video device selected" into a bare "System Firmware Error
// (POST Error)"; on the Quanta's 909 events only 25 read the same.
//
// Left out: ipmitool's vendor-specific suffixes (Dell, Supermicro, Quanta
// OEM decoding, appended in brackets) and its OEM event types 0x70-0x7e.
// None appear in the Quanta's log; such an event shows the standard text
// alone, or no description.

// eventDesc is one row of ipmitool's struct ipmi_event_sensor_types.
type eventDesc struct {
	code, offset, data uint8 // data 0xff: any event data 2
	desc               string
}

// sensorTypeName is ipmi_get_sensor_type: the generic name, or "Unknown"
// (ipmitool names OEM types 0xc0 and up only for Kontron, PICMG and VITA).
func sensorTypeName(code uint8) string {
	if int(code) < len(genericSensorTypes) {
		return genericSensorTypes[code]
	}
	return "Unknown"
}

// eventDescription is ipmi_get_event_desc without the vendor suffixes:
// the generic table by event/reading type, or the sensor-specific one by
// sensor type for type 0x6f; the first row whose offset matches event data
// 1's low nibble and whose data is either "any" or, when event data 2 is
// specified, equal to it.
func eventDescription(eventType, sensorType, d1, d2 uint8) string {
	if eventType >= 0x70 && eventType < 0x7f {
		return ""
	}
	table, code := genericEventTypes, eventType
	if eventType == 0x6f {
		table, code = sensorSpecificEventTypes, sensorType
	}
	offset := d1 & 0x0f
	for _, e := range table {
		if e.code == code && e.offset == offset && (e.data == 0xff || (d1&0xc0 != 0 && e.data == d2)) {
			return strings.TrimSpace(e.desc)
		}
	}
	return ""
}

// selEntryFrom builds one line from a record.
func selEntryFrom(sel *types.SEL) (SELEntry, bool) {
	e := SELEntry{ID: fmt.Sprintf("%x", sel.RecordID)}
	switch {
	case sel.Standard != nil:
		s := sel.Standard
		e.Timestamp = selTime(s.Timestamp)
		e.Event = sensorTypeName(uint8(s.SensorType))
		if s.SensorNumber != 0 {
			e.Event += fmt.Sprintf(" #0x%02x", uint8(s.SensorNumber))
		}
		e.Event += ": " + eventDescription(uint8(s.EventReadingType), uint8(s.SensorType), s.EventData.EventData1, s.EventData.EventData2)
		e.Direction = "Asserted"
		if s.EventDir {
			e.Direction = "Deasserted"
		}
	case sel.OEMTimestamped != nil:
		o := sel.OEMTimestamped
		e.Timestamp = selTime(o.Timestamp)
		// ipmitool prints the three manufacturer ID bytes as stored, least
		// significant first.
		m := uint32(o.ManufacturerID)
		e.Event = fmt.Sprintf("OEM record %02x: %02x%02x%02x %x", uint8(sel.RecordType), m&0xff, m>>8&0xff, m>>16&0xff, o.OEMDefined)
	case sel.OEMNonTimestamped != nil:
		e.Event = fmt.Sprintf("OEM record %02x: %x", uint8(sel.RecordType), sel.OEMNonTimestamped.OEM)
	default:
		return e, false
	}
	return e, true
}

func selTime(t time.Time) string {
	if t.Unix() < 0x20000000 {
		return fmt.Sprintf("Pre-Init %010d", t.Unix())
	}
	return t.Local().Format("2006-01-02 15:04:05 MST")
}

func nativeSEL(host, user, pass string) ([]SELEntry, error) {
	var out []SELEntry
	err := withNative(host, user, pass, ipmiLongTimeout, func(ctx context.Context, c *client.Client) error {
		sels, err := readSEL(ctx, c)
		for _, s := range sels {
			if e, ok := selEntryFrom(s); ok {
				out = append(out, e)
			}
		}
		return err
	})
	return out, err
}

// readSEL reads every SEL record. go-ipmi's GetSELEntries sends Get SEL
// Info before each record as well as once at the start, doubling the
// round trips (34 s against ipmitool's 17 s for the Quanta's 909 records);
// this sends it once, as ipmitool does, then walks the records with the
// library's own request and parser. A record that fails part-way returns
// the records read so far with the error.
func readSEL(ctx context.Context, c *client.Client) ([]*types.SEL, error) {
	info, err := c.GetSELInfo(ctx)
	if err != nil {
		return nil, fmt.Errorf("SEL info: %w", err)
	}
	if info.Entries == 0 {
		return nil, nil
	}
	var out []*types.SEL
	for id := uint16(0); ; {
		res := &storage.GetSELEntryResponse{}
		if err := c.Exchange(ctx, &storage.GetSELEntryRequest{RecordID: id, ReadBytes: 0xff}, res); err != nil {
			return out, fmt.Errorf("SEL record %#04x: %w", id, err)
		}
		sel, err := types.ParseSEL(res.Data)
		if err != nil {
			return out, fmt.Errorf("SEL record %#04x: %w", id, err)
		}
		out = append(out, sel)
		if res.NextRecordID == 0xffff || res.NextRecordID == id {
			return out, nil
		}
		id = res.NextRecordID
	}
}
